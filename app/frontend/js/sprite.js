function getSprite(state) {
  return SPRITES[state] || SPRITES.idle;
}

function renderSprite(ctx, state, scale) {
  const data = getSprite(state);
  scale = scale || 8;

  ctx.clearRect(0, 0, SPRITE_W * scale, SPRITE_H * scale);

  for (let row = 0; row < SPRITE_H; row++) {
    for (let col = 0; col < SPRITE_W; col++) {
      const idx = row * SPRITE_W + col;
      const color = PALETTE[data[idx]];
      if (color) {
        ctx.fillStyle = `rgba(${color[0]},${color[1]},${color[2]},${color[3] / 255})`;
        ctx.fillRect(col * scale, row * scale, scale, scale);
      }
    }
  }
}

// 测试函数（test.html 调用）
function runSpriteTests() {
  const results = [];

  function assert(name, condition) {
    results.push({ name, pass: !!condition });
  }

  // 测试：每个精灵数据长度 = 256
  for (const [name, data] of Object.entries(SPRITES)) {
    assert(`sprite_${name}_length`, data.length === SPRITE_W * SPRITE_H);
  }

  // 测试：调色板映射
  assert('palette_0_transparent', PALETTE[0] === null);
  assert('palette_1_has_color', PALETTE[1] !== null && PALETTE[1].length === 4);
  assert('palette_2_has_color', PALETTE[2] !== null && PALETTE[2].length === 4);

  // 测试：getSprite 返回正确数组
  assert('get_sprite_idle', getSprite('idle') === SPRITES.idle);
  assert('get_sprite_unknown_fallback', getSprite('unknown') === SPRITES.idle);

  // 测试：idle 精灵第一行第一个像素是透明
  assert('idle_pixel_0_0_transparent', SPRITES.idle[0] === 0);

  // 测试：idle 精灵有轮廓像素
  assert('idle_has_outline', SPRITES.idle.some(v => v === 1));

  // 测试：idle 精灵有肤色像素
  assert('idle_has_skin', SPRITES.idle.some(v => v === 2));

  // 测试：talk 精灵有张嘴像素（值为 0 在嘴巴位置）
  assert('talk_has_mouth_open', SPRITES.talk.some(v => v === 0));

  // 测试：所有精灵数据值在 0-5 范围内
  for (const [name, data] of Object.entries(SPRITES)) {
    assert(`sprite_${name}_valid_range`, data.every(v => v >= 0 && v <= 5));
  }

  return results;
}

